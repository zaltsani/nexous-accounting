#!/bin/bash
set -e

psql -h "${PGHOST:-db}" -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
    CREATE EXTENSION IF NOT EXISTS "pg_trgm";

    DO \$\$
    BEGIN
        IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = '${GLITCHTIP_DB_USERNAME}') THEN
            CREATE USER ${GLITCHTIP_DB_USERNAME} WITH PASSWORD '${GLITCHTIP_DB_PASSWORD}';
        END IF;
    END
    \$\$;

    CREATE SCHEMA IF NOT EXISTS glitchtip AUTHORIZATION ${GLITCHTIP_DB_USERNAME};
    GRANT CONNECT, CREATE ON DATABASE ${POSTGRES_DB} TO ${GLITCHTIP_DB_USERNAME};
    GRANT ALL ON SCHEMA glitchtip TO ${GLITCHTIP_DB_USERNAME};
    
    ALTER USER ${GLITCHTIP_DB_USERNAME} SET search_path TO glitchtip, public;
EOSQL